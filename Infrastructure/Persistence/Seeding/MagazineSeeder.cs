    private static Article Create(string title, string lead, Category category, Author author, string coverSeed,
        params ContentBlock[] blocks)
    {
        var article = new Article(title, lead, category.Id, author.Id, Img(coverSeed));
        foreach (var block in blocks)
            article.AddBlock(block);

        return article;
    }

    private static string Img(string seed, int width = 1200, int height = 700) =>
        $"https://picsum.photos/seed/techpulse-{seed}/{width}/{height}";
